#!/bin/sh
# Agent Forge installer for macOS / Linux. Run it from your project's root folder:
#
#   curl -fsSL https://raw.githubusercontent.com/tamtd91ht/agent-forge/main/install.sh | bash
#
# What it does (ADR-0004):
#   1. installs or updates Agent Forge in ~/.agent-forge (its own Python venv + catalog);
#      nothing else on the machine is touched: no PATH change, nothing under ~/.claude
#   2. adds the /agent-forge-upgrade command to the current project (a tracked install that
#      `agent-forge rollback` can undo)
# Then open the project in Claude Code and run /agent-forge-upgrade.
#
# Optional environment variables:
#   AGENT_FORGE_VERSION release tag to install, e.g. v0.1.0 (default: the latest GitHub Release;
#                       falls back to main only when no release can be resolved)
#   AGENT_FORGE_REF     any branch or tag (overrides AGENT_FORGE_VERSION; for development)
#   AGENT_FORGE_SOURCE  pip-installable source instead of the GitHub archive (a local checkout)
set -eu

latest_release() {
    # Prints the tag of the latest GitHub Release, or nothing (no network, no release yet).
    api="https://api.github.com/repos/$1/releases/latest"
    if command -v curl >/dev/null 2>&1; then
        body="$(curl -fsSL --max-time 15 "$api" 2>/dev/null || true)"
    elif command -v wget >/dev/null 2>&1; then
        body="$(wget -qO- --timeout=15 "$api" 2>/dev/null || true)"
    else
        body=""
    fi
    printf '%s' "$body" | tr -d '\n\r' | sed -n 's/.*"tag_name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p'
}

main() {
    repo="tamtd91ht/agent-forge"
    say() { printf 'agent-forge: %s\n' "$1"; }

    # Resolve the ref: explicit AGENT_FORGE_REF > AGENT_FORGE_VERSION > latest release > main.
    # A release tag is pinned content; `main` moves, so it is only the last resort.
    ref="${AGENT_FORGE_REF:-${AGENT_FORGE_VERSION:-}}"
    if [ -z "$ref" ] && [ -z "${AGENT_FORGE_SOURCE:-}" ]; then
        ref="$(latest_release "$repo" || true)"
        if [ -z "$ref" ]; then
            say "could not resolve the latest release; installing from main (set AGENT_FORGE_VERSION to pin)"
            ref="main"
        fi
    fi
    [ -n "$ref" ] || ref="main"
    source="${AGENT_FORGE_SOURCE:-https://github.com/$repo/archive/$ref.zip}"
    home_dir="${AGENT_FORGE_INSTALL_DIR:-$HOME/.agent-forge}"
    venv="$home_dir/.venv"
    bin="$home_dir/bin"
    project="$(pwd)"


    # 1. Python >= 3.11
    py=""
    for cand in python3 python; do
        if command -v "$cand" >/dev/null 2>&1 &&
            [ "$("$cand" -c 'import sys; print(int(sys.version_info >= (3, 11)))' 2>/dev/null)" = "1" ]; then
            py="$cand"
            break
        fi
    done
    if [ -z "$py" ]; then
        say "Python 3.11 or newer is required. Install it (https://www.python.org/downloads/) and re-run this command."
        exit 1
    fi

    # 2. engine in ~/.agent-forge/.venv
    mkdir -p "$home_dir" "$bin"
    if [ ! -x "$venv/bin/python" ]; then
        say "creating $venv"
        "$py" -m venv "$venv"
    fi
    say "installing Agent Forge $ref from $source"
    "$venv/bin/python" -m pip install --quiet --disable-pip-version-check --upgrade --force-reinstall "$source"

    # 3. launcher used by Claude Code
    cat >"$bin/agent-forge" <<'EOF'
#!/bin/sh
# Agent Forge launcher (generated by install.sh)
d="$(cd "$(dirname "$0")/.." && pwd)"
export AGENT_FORGE_HOME="$d"
if [ -x "$d/.venv/bin/agent-forge" ]; then exec "$d/.venv/bin/agent-forge" "$@"; fi
exec "$d/.venv/Scripts/agent-forge.exe" "$@"
EOF
    chmod +x "$bin/agent-forge"
    af="$bin/agent-forge"

    # 4. catalog (workspace) in ~/.agent-forge
    if [ -f "$home_dir/agent-forge.yaml" ]; then
        "$af" init --workspace "$home_dir" --refresh-registry >/dev/null
    else
        "$af" init --workspace "$home_dir" >/dev/null
    fi
    say "installed in $home_dir"

    # 5. the /agent-forge-upgrade command in this project
    case "$project" in
        "$HOME" | "$home_dir" | "$home_dir"/*)
            say "run this command again from your project root to add /agent-forge-upgrade to it."
            return 0
            ;;
    esac
    "$af" setup "$project"
}

main "$@"
