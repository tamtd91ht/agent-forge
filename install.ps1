# Agent Forge installer for Windows. Run it from your project's root folder:
#
#   irm https://raw.githubusercontent.com/tamtd91ht/agent-forge/main/install.ps1 | iex
#
# What it does (ADR-0004):
#   1. installs or updates Agent Forge in ~/.agent-forge (its own Python venv + catalog);
#      nothing else on the machine is touched: no PATH change, nothing under ~/.claude
#   2. adds the /agent-forge-upgrade command to the current project (a tracked install that
#      `agent-forge rollback` can undo)
# Then open the project in Claude Code and run /agent-forge-upgrade.
#
# Optional environment variables:
#   AGENT_FORGE_VERSION release tag to install, e.g. v0.1.0 (default: the latest GitHub Release;
#                       falls back to main only when no release can be resolved)
#   AGENT_FORGE_REF     any branch or tag (overrides AGENT_FORGE_VERSION; for development)
#   AGENT_FORGE_SOURCE  pip-installable source instead of the GitHub archive (a local checkout)

& {
    $ErrorActionPreference = 'Stop'
    $Repo = 'tamtd91ht/agent-forge'
    function Say($msg) { Write-Host "agent-forge: $msg" }

    # Resolve the ref: explicit AGENT_FORGE_REF > AGENT_FORGE_VERSION > latest release > main.
    # A release tag is pinned content; `main` moves, so it is only the last resort.
    $Ref = if ($env:AGENT_FORGE_REF) { $env:AGENT_FORGE_REF } elseif ($env:AGENT_FORGE_VERSION) { $env:AGENT_FORGE_VERSION } else { $null }
    if (-not $Ref -and -not $env:AGENT_FORGE_SOURCE) {
        try {
            [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
            $latest = Invoke-RestMethod -Uri "https://api.github.com/repos/$Repo/releases/latest" -TimeoutSec 15 -Headers @{ 'User-Agent' = 'agent-forge-installer' }
            if ($latest.tag_name) { $Ref = [string]$latest.tag_name }
        } catch { $Ref = $null }
        if (-not $Ref) {
            Say 'could not resolve the latest release; installing from main (set AGENT_FORGE_VERSION to pin)'
            $Ref = 'main'
        }
    }
    if (-not $Ref) { $Ref = 'main' }
    $Source = if ($env:AGENT_FORGE_SOURCE) { $env:AGENT_FORGE_SOURCE } else { "https://github.com/$Repo/archive/$Ref.zip" }
    $Home_ = if ($env:AGENT_FORGE_INSTALL_DIR) { $env:AGENT_FORGE_INSTALL_DIR } else { Join-Path $HOME '.agent-forge' }
    $Venv = Join-Path $Home_ '.venv'
    $Bin = Join-Path $Home_ 'bin'
    $Project = (Get-Location).Path

    # 1. Python >= 3.11
    $py = $null
    foreach ($cand in @(@('py', '-3'), @('python'), @('python3'))) {
        $exe = $cand[0]
        if (-not (Get-Command $exe -ErrorAction SilentlyContinue)) { continue }
        $pyArgs = @($cand | Select-Object -Skip 1)
        $ok = & $exe @pyArgs -c 'import sys; print(int(sys.version_info >= (3, 11)))' 2>$null
        if ($LASTEXITCODE -eq 0 -and "$ok".Trim() -eq '1') { $py = $cand; break }
    }
    if (-not $py) {
        Say 'Python 3.11 or newer is required. Install it from https://www.python.org/downloads/ and re-run this command.'
        return
    }

    # 2. engine in ~/.agent-forge/.venv
    New-Item -ItemType Directory -Force -Path $Home_, $Bin | Out-Null
    $venvPy = Join-Path $Venv 'Scripts\python.exe'
    if (-not (Test-Path $venvPy)) {
        Say "creating $Venv"
        $pyArgs = @($py | Select-Object -Skip 1)
        & $py[0] @pyArgs -m venv $Venv
        if ($LASTEXITCODE -ne 0) { throw 'could not create the virtual environment' }
    }
    Say "installing Agent Forge $Ref from $Source"
    & $venvPy -m pip install --quiet --disable-pip-version-check --upgrade --force-reinstall $Source
    if ($LASTEXITCODE -ne 0) { throw 'pip install failed' }

    # 3. launchers: agent-forge (bash, used by Claude Code) and agent-forge.cmd (PowerShell / cmd)
    $sh = "#!/bin/sh`n# Agent Forge launcher (generated by install.ps1)`nd=`"`$(cd `"`$(dirname `"`$0`")/..`" && pwd)`"`nexport AGENT_FORGE_HOME=`"`$d`"`nif [ -x `"`$d/.venv/bin/agent-forge`" ]; then exec `"`$d/.venv/bin/agent-forge`" `"`$@`"; fi`nexec `"`$d/.venv/Scripts/agent-forge.exe`" `"`$@`"`n"
    [IO.File]::WriteAllText((Join-Path $Bin 'agent-forge'), $sh)
    $cmd = "@echo off`r`nrem Agent Forge launcher (generated by install.ps1)`r`nset `"AGENT_FORGE_HOME=%~dp0..`"`r`n`"%~dp0..\.venv\Scripts\agent-forge.exe`" %*`r`n"
    [IO.File]::WriteAllText((Join-Path $Bin 'agent-forge.cmd'), $cmd)
    $af = Join-Path $Bin 'agent-forge.cmd'

    # 4. catalog (workspace) in ~/.agent-forge
    if (Test-Path (Join-Path $Home_ 'agent-forge.yaml')) {
        & $af init --workspace $Home_ --refresh-registry | Out-Null
    } else {
        & $af init --workspace $Home_ | Out-Null
    }
    if ($LASTEXITCODE -ne 0) { throw 'could not prepare the Agent Forge workspace' }
    Say "installed in $Home_"

    # 5. the /agent-forge-upgrade command in this project
    $resolvedHome = (Resolve-Path $HOME).Path.TrimEnd('\')
    if ($Project.TrimEnd('\') -eq $resolvedHome -or $Project.StartsWith((Resolve-Path $Home_).Path)) {
        Say 'run this command again from your project root to add /agent-forge-upgrade to it.'
        return
    }
    & $af setup $Project
    if ($LASTEXITCODE -ne 0) { throw 'could not add /agent-forge-upgrade to this project' }
}
